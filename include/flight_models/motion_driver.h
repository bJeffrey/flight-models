/** @file Bounded waypoint guidance, scheduled controls, and typed state samples. */
#pragma once

#include "flight_models/motion_profile.h"
#include "flight_models/state_store.h"

#include <cstddef>
#include <cstdint>
#include <memory>
#include <vector>

namespace flight_models {

/** Explicit bounds for admitted programs and per-advance generated work. */
struct DriverLimits {
  std::size_t max_commands{}; /**< Maximum admitted commands across the cohort. */
  std::size_t max_waypoints{}; /**< Maximum admitted waypoints across the cohort. */
  std::size_t max_samples{}; /**< Maximum samples retained across one advance. */
  std::size_t max_transitions{}; /**< Maximum transitions retained across one advance. */
  std::size_t max_events{}; /**< Maximum event boundaries processed in one advance. */
};

/** ECEF waypoint position, metres. */
struct Waypoint { math::Vector3 position_ecef_m{}; };

/** Complete desired-motion target scheduled at scenario nanoseconds. */
struct TimedDesiredMotion {
  std::int64_t time_ns{}; /**< Event time, scenario nanoseconds. */
  std::uint64_t sequence{}; /**< Per-entity unique ordering identity. */
  DesiredMotion desired{}; /**< Heading rad, horizontal speed m/s, HAE m. */
};

/** Typed program bound to one current store handle. */
struct EntityProgram {
  Handle entity{}; /**< Current state-store entity. */
  bool navigation_reporting{}; /**< Emit navigation samples on the profile cadence. */
  std::vector<Waypoint> waypoints; /**< Ordered canonical ECEF route. */
  std::vector<TimedDesiredMotion> commands; /**< Ordered desired-motion events. */
};

/** Physical-truth or configured navigation-model input sampling cadence. */
enum class SampleKind : std::uint8_t { physical, navigation };

/** One physical or configured navigation publication snapshot. */
struct TimedStateSample {
  Handle entity{}; /**< Sampled entity handle. */
  SampleKind kind{}; /**< Physical before navigation at a shared event time. */
  PhysicalState state{}; /**< State and source time at the event boundary. */
  DesiredMotion desired{}; /**< Active full desired target at the boundary. */
};

/** Ordered waypoint capture at an exact scenario timestamp. */
struct WaypointTransition {
  Handle entity{}; /**< Captured entity. */
  std::size_t waypoint_index{}; /**< Zero-based captured waypoint. */
  std::int64_t time_ns{}; /**< Capture time, scenario nanoseconds. */
};

/**
 * Single-owner event driver for one fixed profile cohort in a fresh run.
 * Programs and store membership must remain fixed for the driver's lifetime.
 */
class MotionDriver {
 public:
  /**
   * Validate the fixed enabled cohort, commands, waypoints and limits, then
   * reserve reusable workspaces. The store and outputs remain untouched until
   * the first successful advance processes time zero transactionally.
   * @param store Single-owner source store, unchanged by outside lifecycle edits.
   * @param profile_index Selected model profile shared by every enabled cohort row.
   * @param profile Immutable admitted motion, capture, integration and cadence policy.
   * @param limits Explicit bounds for input and generated event work.
   * @param programs Exactly one program for each enabled entity in the profile.
   * @throws std::invalid_argument for invalid profile, stale/duplicate/missing
   *         programs, incompatible route/command inputs, or out-of-envelope data.
   * @throws std::length_error when an explicit input or output bound is exceeded.
   */
  MotionDriver(StateStore& store, std::size_t profile_index, MotionProfile profile,
               DriverLimits limits, std::vector<EntityProgram> programs);
  ~MotionDriver();
  MotionDriver(MotionDriver&&) noexcept;
  MotionDriver& operator=(MotionDriver&&) noexcept;
  MotionDriver(const MotionDriver&) = delete;
  MotionDriver& operator=(const MotionDriver&) = delete;

  /**
   * Advance transactionally through command, capture and sample events.
   * @param time_ns Nonnegative scenario time, monotonic and within the profile interval bound.
   * @throws std::invalid_argument for invalid time, changed store membership,
   *         invalid staged state, numerical failure, or exhausted substep budget.
   * @throws std::length_error when event, sample or transition limits are exceeded.
   * Any failure leaves the store, driver time, progress and last successful outputs unchanged.
   */
  void advance_to(std::int64_t time_ns);
  /** Last successfully committed scenario time, initially zero. */
  std::int64_t time_ns() const noexcept;
  /**
   * Samples generated by the last successful advance, including initial samples
   * on the first success; valid until the next successful advance.
   */
  const std::vector<TimedStateSample>& samples() const noexcept;
  /** Waypoint transitions generated by the last successful advance; valid until the next success. */
  const std::vector<WaypointTransition>& transitions() const noexcept;
  /** @throws std::invalid_argument if entity is not in this driver's cohort. */
  std::size_t waypoint_progress(Handle entity) const;

 private:
  struct Impl;
  std::unique_ptr<Impl> impl_;
};

}  // namespace flight_models
